"""Builds 03_extract/README_sdmx.md from the tidy outputs, manifests and anchor-check files.
Run: python -I scripts/build_readme_sdmx.py"""
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EX, RAW = ROOT / "03_extract", ROOT / "02_raw"


def rd(p):
    with open(p, newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def yrs(rows):
    ys = sorted({r["year"] for r in rows if r["year"]})
    return f"{ys[0]}-{ys[-1]}" if ys else "n/a"


L = []
w = L.append
w("# SDMX extraction: Indonesia bilateral travel services (BPM6 item SD)")
w("")
w("Generated by `scripts/build_readme_sdmx.py` from the files below. All flows are from Indonesia's point of view "
  "(credit = foreigners' spending in Indonesia; debit = Indonesian residents' spending abroad). "
  "Values are in millions (unit_mult = 6); currency is USD / EUR for the exchange-rate-converted series and "
  "XDC = the reporter's national currency (OECD TIS only). Balance rows for mirror sources are the reporter's balance with the sign flipped.")
w("")
w("## Files")
w("| File | Rows |")
w("|---|---|")
bat, tis, eus = rd(EX / "batis.csv"), rd(EX / "mirror_oecd_tis.csv"), rd(EX / "mirror_eurostat.csv")
chk = rd(EX / "batis_reported_check.csv")
for n, rows in (("batis.csv", bat), ("mirror_oecd_tis.csv", tis), ("mirror_eurostat.csv", eus), ("batis_reported_check.csv", chk)):
    w(f"| 03_extract/{n} | {len(rows):,} |")
w("")
w("Raw responses (unchanged) with `manifest.csv` (file, url, retrieved_at_utc, sha256, http_status, rows) are in "
  "`02_raw/batis/`, `02_raw/oecd_tis/`, `02_raw/eurostat/`. Failed/empty probes are stored as `*.http<status>.txt`. "
  "Scripts: `scripts/fetch_batis.py`, `fetch_oecd_tis.py`, `fetch_eurostat.py` (shared helpers in `sdmx_common.py`; run with `python -I`; "
  "re-runs reuse cached raw files, `--refresh` re-downloads). Per-source anchor results: `03_extract/anchor_checks_*.csv`.")
w("")
w("Raw manifest summary:")
w("")
w("| Folder | file | http_status | rows | retrieved_at_utc |")
w("|---|---|---|---|---|")
for d in ("batis", "oecd_tis", "eurostat"):
    for r in rd(RAW / d / "manifest.csv"):
        w(f"| {d} | {r['file']} | {r['http_status']} | {r['rows']} | {r['retrieved_at_utc']} |")
w("")

# ---- BaTIS ----
w("## 1. OECD-WTO BaTIS (batis.csv)")
a = [r for r in bat if r["line"] == "A_model"]
b = [r for r in bat if r["line"] == "A_model_partnerside"]
w(f"- A_model (Indonesia as reporter): {len(a):,} rows; years {yrs(a)}; {len({r['partner_iso3'] for r in a})} counterpart codes (incl. W = World and former-country codes ANT_F, SCG_F); items {sorted({r['item'] for r in a})}.")
w(f"- A_model_partnerside (partners reporting Indonesia, flipped): {len(b):,} rows; years {yrs(b)}; {len({r['reporter'] for r in b})} reporter codes.")
cnt = defaultdict(int)
for r in bat:
    cnt[(r["line"], r["adjustment"])] += 1
w("- Rows by line x ADJUSTMENT: " + "; ".join(f"{k[0]}/{k[1]}={v:,}" for k, v in sorted(cnt.items())))
w("- SDA (business) and SDB (personal) DO return data in BaTIS (all three adjustment types).")
w("- UNIT_MULT = 6 (millions), UNIT_MEASURE = USD_EXC for every row. BaTIS carries no balance rows (derive as credit - debit if needed).")
w("- methodology_type is blank for ADJUSTMENT B rows (balanced) and for a few F rows (the 2 World-total rows per year x item, W credit/debit); ME/IE/AG/DE only apply to N/F rows.")
bad = sum(int(r["n_reported_rows_partner_not_world"]) for r in chk)
w(f"- `batis_reported_check.csv`: IDN-reported (ADJUSTMENT=N) rows with partner != World, summed over all years and items = **{bad}** "
  f"({'confirms Indonesia reports World only' if bad == 0 else 'UNEXPECTED: nonzero'}). Method mix of F rows per year is in the same file "
  "(columns F_AG, F_IE, F_ME, F_blank).")
sd = [r for r in chk if r["item"] == "SD"]
w("  SD F-row method mix by year (ME / IE / AG / blank): " + "; ".join(f"{r['year']}: {r['F_ME']}/{r['F_IE']}/{r['F_AG']}/{r['F_blank']}" for r in sd))
w("")

# ---- TIS ----
w("## 2. OECD TIS partner-reported mirror (mirror_oecd_tis.csv)")
w(f"- {len(tis):,} rows; years {yrs(tis)}; annual only (quarter blank); measures {sorted({r['item'] for r in tis})}; currencies {sorted({r['currency'] for r in tis})}; adjustment {sorted({r['adjustment'] for r in tis})}.")
names = {r["REF_AREA"]: r["Reference area"] for r in rd(RAW / "oecd_tis" / "tis_idn_annual_and_quarterly_request.csv")}
rep_all = sorted({r["reporter"] for r in tis})
sdrep = defaultdict(list)
for r in tis:
    if r["item"] == "SD" and r["value"] != "":
        sdrep[r["reporter"]].append(int(r["year"]))
w(f"- Reporters in file (any measure): {len(rep_all)}. Reporters with non-empty Indonesia **SD** (total travel) data: {len(sdrep)} (EU27_2020 is an aggregate, not a country):")
w("  " + ", ".join(f"{k} ({min(v)}-{max(v)})" for k, v in sorted(sdrep.items())))
nosd = [x for x in rep_all if x not in sdrep]
w(f"- Reporters with sub-items only (no SD total): {nosd} ({', '.join(names[x] for x in nosd)}).")
w("- Valid travel MEASURE codes confirmed from the DSD (`dsd_DF_TIS_references_all.xml`): SD, SD1-SD5, SDA, SDA1, SDA2, SDB, SDB1, SDB2, SDB3. "
  "Only SD, SDA, SDB, SDB1, SDB2, SDB3 were fetched, as requested (SD1-SD5, SDA1, SDA2 not fetched).")
w("- Quarterly: the combined A+Q request returned annual rows only; an explicit Q request returns HTTP 404 NoResultsFound. No quarterly OECD TIS data for counterpart IDN.")
w("")

# ---- Eurostat ----
w("## 3. Eurostat bop_its6_det, partner = ID (mirror_eurostat.csv)")
w(f"- {len(eus):,} rows; years {yrs(eus)}; annual only; items {sorted({r['item'] for r in eus})}; currency EUR (MIO_EUR, not converted).")
conf = sum(1 for r in eus if "conf:C" in r["obs_status"])
blank = sum(1 for r in eus if r["value"] == "")
w(f"- obs_status holds OBS_FLAG (p provisional, e estimated, u low reliability) and `conf:C` for CONF_STATUS = C (confidential). "
  f"{conf:,} rows are confidential and have an EMPTY value ({blank:,} rows with empty value in total).")
sde = defaultdict(list)
for r in eus:
    if r["item"] == "SD" and r["value"] != "":
        sde[r["reporter"]].append(int(r["year"]))
w(f"- Reporters with non-empty Indonesia **SD** data: {len(sde)} (EU27_2020 is an aggregate; Eurostat geo codes mapped to ISO3, EL->GRC, UK->GBR, XK->XKX):")
w("  " + ", ".join(f"{k} ({min(v)}-{max(v)})" for k, v in sorted(sde.items())))
w("- Quarterly (Q, SD): HTTP 400 INVALID_QUERY_DIMENSION_VALUE (FREQ=Q not allowed in bop_its6_det). No quarterly data.")
w("- Do not sum EU27_2020 with its member states (aggregate overlaps members). Overlap with OECD TIS reporters (e.g. FRA, ITA, NLD) is expected: same national statistics, different publisher/currency.")
w("")

# ---- Anchors ----
w("## Anchor checks")
w("| Source | Anchor | Expected | Got | Result |")
w("|---|---|---|---|---|")
tot = fail = 0
for s in ("batis", "oecd_tis", "eurostat"):
    for r in rd(EX / f"anchor_checks_{s}.csv"):
        w(f"| {s} | {r['anchor']} | {r['expected']} | {r['got']} | {r['status']} |")
        tot += 1
        fail += r["status"] != "PASS"
w("")
w(f"**{tot - fail}/{tot} anchors PASS.** Tolerance = half a unit of the last decimal place quoted in the brief (BaTIS values rounded to 2 decimals).")
w("")
w("## Problems and notes")
w("- No HTTP errors on the data requests that returned data; no retry/backoff messages were logged during the runs.")
w("- The `.../dataflow/OECD.SDD.TPS/DF_TIS/1.0?references=all` structure URL returns 404; the working form is `.../dataflow/OECD.SDD.TPS/DSD_BOP@DF_TIS/1.0?references=all`.")
w("- OECD TIS currency: the source CURRENCY field is `_Z` (not applicable); `currency` here is derived from UNIT_MEASURE (USD_EXC->USD, EUR_EXC->EUR, XDC->XDC). Filter `currency == 'USD'` for the primary series.")
w("- OECD TIS reporters absent for Indonesia travel: e.g. CHN, MYS, SGP, SAU, KOR, THA, IND; DEU has sub-items only. These need other sources.")
w("- BaTIS partner-side file contains aggregate/former-country reporters (e.g. ANT_F, SCG_F) and 'W'; filter before summing across partners.")
w("- BaTIS: Indonesia's own (N) data are world totals only; partner splits are modelled (see check file). 2023-2024 are mostly IE (interpolation/extrapolation).")
w("- Mirror-source `value` for flow_idn = balance is the negated reporter balance; credit/debit are swapped from the reporter's own labels.")
(EX / "README_sdmx.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("README written;", tot - fail, "/", tot, "anchors pass")
